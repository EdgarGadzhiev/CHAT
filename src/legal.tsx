export function DocSheet({ id, onClose }: { id: string; onClose: () => void }) {
  const d = docs()[id]
  if (!d) return null
  return (
    <Sheet title={d.title} kicker={`Версия ${POLICY_VERSION}`} onClose={onClose}>
      <div className="doc">
        {d.sections.map((s) => (
          <section key={s.h}>
            <h3>{s.h}</h3>
            {s.p.map((t, i) => <p key={i}>{t}</p>)}
          </section>
        ))}
      </div>
    </Sheet>
  )
}

export function DocLinks({ ids }: { ids: [string, string][] }) {
  const [open, setOpen] = useState<string | null>(null)
  return (
    <>
      {ids.map(([id, label]) => (
        <button key={id} className="link" onClick={() => setOpen(id)}>{label}</button>
      ))}
      {open && <DocSheet id={open} onClose={() => setOpen(null)} />}
    </>
  )
}
